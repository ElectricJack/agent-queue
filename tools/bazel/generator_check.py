"""Byte-level tracked drift and independent, locked TypeScript parity check."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from tools.bazel.generate import compare, manifest
from tools.bazel.generator_inputs import npm_closure, render_inputs


def check(root: Path, tracked: Path, typescript: Path, reference: Path) -> None:
    if (root / "tools/bazel/generator_inputs.bzl").read_text() != render_inputs(root):
        raise ValueError("generator source inventory drift; run generator_inputs.py --write")
    locked = json.loads((root / "tools/bazel/generator_npm.lock.json").read_text())
    if locked != npm_closure(root):
        raise ValueError("npm generator closure drift; run generator_inputs.py --write")
    differences = []
    for relative, digest in manifest(tracked).items():
        expected = root / relative
        import hashlib

        if not expected.is_file() or hashlib.sha256(expected.read_bytes()).hexdigest() != digest:
            differences.append(relative)
    # A removed generator output is drift too, including stale client modules.
    for directory in ("packages/aq-client", "docs/reference/playbook-commands"):
        expected_files = manifest(root / directory, allow_symlinks=True)
        actual_files = manifest(tracked / directory)
        if expected_files != actual_files:
            differences.append(directory + " file manifest")
    if differences:
        raise ValueError("tracked generated byte drift:\n" + "\n".join(differences))
    if not manifest(typescript):
        raise ValueError("missing TypeScript output")
    compare(reference, typescript)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tracked", type=Path, required=True)
    parser.add_argument("--typescript", type=Path, required=True)
    parser.add_argument("--reference", type=Path, required=True)
    args = parser.parse_args()
    # Bazel tests start in the main repository's runfiles directory.
    check(Path.cwd(), args.tracked, args.typescript, args.reference)
    print("Tracked outputs and independent TypeScript bytes: exact")


if __name__ == "__main__":
    main()
