"""Run legacy generators with declared tools in private, writable scratch trees.

This executable is an action tool, not a new regeneration implementation. Its
outputs are ordinary directory artifacts, with relative SHA-256 manifests.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def manifest(root: Path, *, allow_symlinks: bool = False) -> dict[str, str]:
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink() and not allow_symlinks:
            raise ValueError(f"generated output must not be a symlink: {path.relative_to(root)}")
        if path.is_file() and not any(p in {"__pycache__", ".ruff_cache"} for p in path.parts):
            result[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


def compare(expected: Path, actual: Path) -> None:
    left, right = manifest(expected), manifest(actual)
    differences = [name for name in sorted(left.keys() | right.keys())
                   if left.get(name) != right.get(name)]
    if differences:
        raise ValueError("generated byte/filename drift:\n" + "\n".join(differences))


def copy_inputs(inputs: list[list[str]], destination: Path) -> None:
    for source, relative in inputs:
        path = Path(relative)
        if path.is_absolute() or ".." in path.parts:
            raise ValueError(f"unsafe generator input: {relative}")
        output = destination / path
        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, output)
        output.chmod(Path(source).stat().st_mode & 0o777)


def environment(base: Path, native: Path, node: Path | None, ruff: Path) -> dict[str, str]:
    """Positive allowlist; no worker credentials, config or installed-client hooks."""
    home = base / "home"
    home.mkdir()
    temporary = base / "tmp"
    temporary.mkdir()
    binary = base / "bin"
    binary.mkdir()
    # Keep rules_python's declared wheel paths across the legacy script's child
    # interpreters. The scratch source root is prepended by execute(), below.
    python_paths = [str(Path(p).resolve()) for p in sys.path if p and Path(p).is_dir()]
    bash = native / "bin/bash"
    for name, module in (("python", None), ("python3", None),
                         ("openapi-python-client", "openapi_python_client")):
        arguments = "" if module is None else " -m " + module
        # Paths are supplied by Bazel, but still quote them as shell data.
        import shlex

        (binary / name).write_text(
            f"#!{bash}\nexec {shlex.quote(sys.executable)}{arguments} \"$@\"\n"
        )
        (binary / name).chmod(0o755)
    # The wheel's native binary is outside site-packages. Its Python launcher
    # searches ambient installation layouts, which do not apply in runfiles.
    (binary / "ruff").symlink_to(ruff)
    if node is not None:
        (binary / "node").symlink_to(node)
    return {
        "PATH": f"{binary}:{native / 'bin'}",
        "LD_LIBRARY_PATH": str(native / "lib"),
        "PYTHONPATH": os.pathsep.join(python_paths),
        "PYTHONNOUSERSITE": "1",
        "PYTHONDONTWRITEBYTECODE": "1",
        "PYTHONHASHSEED": "0",
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_ATTR_NOSYSTEM": "1",
        "GIT_TERMINAL_PROMPT": "0",
        "HOME": str(home),
        "XDG_CONFIG_HOME": str(home / ".config"),
        "XDG_CACHE_HOME": str(home / ".cache"),
        "TMPDIR": str(temporary),
        "LANG": "C.UTF-8",
        "LC_ALL": "C.UTF-8",
        "TZ": "UTC",
        "AQ_DB_SCOPE": "worker",
        "AQ_GENERATOR_PYTHON": sys.executable,
    }


def run(command: list[str], root: Path, env: dict[str, str]) -> str:
    result = subprocess.run(command, cwd=root, env=env, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, timeout=600)
    if result.returncode:
        raise RuntimeError(f"generator failed ({result.returncode}): {command}\n{result.stdout}")
    return result.stdout


def tracked_paths(root: Path, env: dict[str, str], bash: str) -> list[str]:
    paths = run([bash, "scripts/regenerate-generated.sh", "--list"], root, env).splitlines()
    # Command pages contain authored prose around generated blocks, so their
    # complete existing bytes are inputs and their complete files are outputs.
    paths.remove("docs/reference/playbook-commands/README.md")
    paths.append("docs/reference/playbook-commands")
    # The umbrella script also projects blocks in otherwise authored profiles.
    paths.extend(p.relative_to(root).as_posix()
                 for p in sorted((root / "src/profiles/defaults").glob("worker-*/profile.md")))
    return sorted(set(paths))


def initialize_git(root: Path, native: Path, env: dict[str, str]) -> None:
    git = str(native / "bin/git")
    run([git, "init", "-q"], root, env)
    run([git, "add", "-A"], root, env)
    run([git, "-c", "user.name=generator", "-c", "user.email=generator@localhost",
         "commit", "-q", "-m", "declared generator inputs"], root, env)


def export(root: Path, paths: list[str], output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    for relative in paths:
        source = root / relative
        destination = output / relative
        if source.is_dir():
            shutil.copytree(source, destination, ignore=shutil.ignore_patterns(
                "__pycache__", "*.pyc", ".ruff_cache",
            ))
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, destination)


def assert_portable(root: Path, forbidden: list[Path]) -> None:
    for relative in manifest(root):
        content = (root / relative).read_bytes()
        for path in forbidden:
            if str(path).encode() in content:
                raise ValueError(f"temporary/execroot path in generated output: {relative}")


def execute(args: argparse.Namespace) -> None:
    inputs = [[str(Path(source).resolve()), relative]
              for source, relative in json.loads(args.inputs.read_text())]
    native = args.native.resolve()
    node = args.node.resolve() if args.node else None
    npm = args.npm.resolve() if args.npm else None
    upstream = args.upstream.resolve() if args.upstream else None
    output = args.output.resolve()
    # Use the action's writable cwd, never a checkout or shared environment.
    with tempfile.TemporaryDirectory(prefix="aq-generator-", dir=Path.cwd()) as temporary:
        base = Path(temporary)
        root = base / "tree"
        root.mkdir()
        copy_inputs(inputs, root)
        env = environment(base, native, node, args.ruff.resolve())
        env["PYTHONPATH"] = str(root) + os.pathsep + env["PYTHONPATH"]
        bash = str(native / "bin/bash")
        if args.kind == "tracked":
            # Provenance checks in the legacy entrypoint require a Git index.
            # This index contains only declared inputs; no operator history/config.
            initialize_git(root, native, env)
            paths = tracked_paths(root, env, bash)
            run([bash, "scripts/regenerate-generated.sh"], root, env)
            export(root, paths, output)
        else:
            if upstream is None or npm is None or node is None:
                raise ValueError("TypeScript generation needs declared OpenAPI, npm and Node inputs")
            shutil.copyfile(upstream / "openapi.json", root / "openapi.json")
            (root / "node_modules").symlink_to(npm)
            if args.kind == "typescript":
                run([bash, "scripts/regenerate-ts-client.sh", "--from-file"], root, env)
            else:
                initialize_git(root, native, env)
                run([bash, "scripts/regenerate-api-client.sh", "--offline"], root, env)
                # Independent parity reference: invoke the locked legacy tool
                # directly, not the adapter or the generated output artifact.
                run([str(node), str(npm / "@hey-api/openapi-ts/bin/index.cjs"),
                     "--input", str(root / "openapi.json"),
                     "--output", str(root / "packages/aq-ts-client/src"),
                     "--client", "@hey-api/client-fetch"], root, env)
                run([bash, "scripts/regenerate-generated.sh", "--check"], root, env)
                run([str(native / "bin/git"), "diff", "--exit-code"], root, env)
                untracked = run([str(native / "bin/git"), "ls-files", "--others",
                                 "--exclude-standard"], root, env)
                if untracked.strip():
                    raise ValueError("untracked generated outputs: " + untracked)
            export(root, ["packages/aq-ts-client/src"], output)
        assert_portable(output, [base, Path.cwd(), native])
        if args.manifest:
            args.manifest.write_text(json.dumps(manifest(output), indent=2, sort_keys=True) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--native", type=Path, required=True)
    parser.add_argument("--ruff", type=Path, required=True)
    parser.add_argument("--node", type=Path)
    parser.add_argument("--npm", type=Path)
    parser.add_argument("--upstream", type=Path)
    parser.add_argument("--kind", choices=("tracked", "typescript", "typescript_reference"),
                        required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--manifest", type=Path)
    execute(parser.parse_args())


if __name__ == "__main__":
    main()
