def git(repo: Path, *args: str) -> str:
    """Run git in *repo* and return its stdout; a nonzero status raises."""
    return subprocess.run(
        ["git", *args], cwd=repo, check=True, capture_output=True, text=True
    ).stdout


def build_fixture_repo(root: Path) -> Path:
    """Create the fixture project at *root*, commit it on ``main`` and give it an ``origin``.

    Returns *root*. ``origin/main`` resolves to the single base commit and the
    working tree is clean.
    """
    root.mkdir(parents=True)
    git(root, "init", "-q", "-b", "main")
    # Repository-local identity: a CI runner has no global one, and a box's
    # global signing or hook settings must not reach the fixture's commits.
    git(root, "config", "user.name", "Selection Fixture")
    git(root, "config", "user.email", "fixture@example.invalid")
    git(root, "config", "commit.gpgsign", "false")
    git(root, "config", "core.hooksPath", "/dev/null")
    # Anything that imports the fixture's modules must not dirty its tree.
    (root / ".git" / "info" / "exclude").write_text("__pycache__/\n*.pyc\n")
    for relative, text in FILES.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    _write_catalogue(root)
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "fixture base")
    origin = root.with_name(root.name + ".origin.git")
    git(root.parent, "clone", "-q", "--bare", str(root), str(origin))
    git(root, "remote", "add", "origin", str(origin))
    git(root, "fetch", "-q", "origin")
    return root


def _write_catalogue(root: Path) -> None:
    """Write ``tests/selection_catalogue.json`` with the catalogue generator.

    The generator (``src.test_selection.catalogue``) and this fixture were
    written by sibling tasks of the same plan that start together, so until
    both have landed the fixture is built without the catalogue; nothing the
    change snapshot checks reads it. Once the module exists it is always used.
    """
    if importlib.util.find_spec("src.test_selection.catalogue") is None:
        return
    from src.test_selection import catalogue

    areas = catalogue.load_areas(root / catalogue.AREAS_PATH)
    built = catalogue.build_catalogue(root, areas)
    (root / catalogue.CATALOGUE_PATH).write_text(catalogue.render_catalogue(built))
