"""A small git project shaped like this one, for the test-selection tests.

Tasks 2-4, 9 and 13 of the smart-test-selection plan share it: the change
snapshot, the mandatory set, the static-impact adapter, the selection service
and the replay harness all run against the same committed tree and its
reviewed ``tests/selection_*`` artifacts, so a fact one of them relies on (an
area, an ownership rule, a function-local import) is written down once.

The layout, every file committed in the base commit on ``main``:

.. code-block:: text

    pyproject.toml            [tool.pytest.ini_options] testpaths = ["tests"]
    src/pkg/__init__.py       (empty)
    src/pkg/a.py              def alpha(): return 1
    src/pkg/b.py              def beta(): from .a import alpha; return alpha() + 1  (function-local import)
    src/pkg/c.py              def gamma(): return 3
    src/pkg/data.json         {"k": 1}
    docs/README.md            "# docs"
    tests/conftest.py         (empty)
    tests/test_a.py           imports src.pkg.a
    tests/sub/__init__.py, tests/sub/conftest.py (a fixture), tests/sub/test_b.py (imports src.pkg.b)
    tests/test_c.py           imports src.pkg.c
    tests/test_docs_scan.py   reads docs/README.md
    tests/selection_areas.yaml, tests/selection_rules.yaml, tests/selection_policy.yaml
    tests/selection_catalogue.json  (generated by src.test_selection.catalogue)

``origin`` is a bare clone beside the repository (``<root>.origin.git``), so
``origin/main`` resolves and the working tree is clean.
"""

