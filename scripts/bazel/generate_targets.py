#!/usr/bin/env python3
"""Generate package libraries, module tests and exact workflow obligations.

Refresh collection (never executes tests), then generate::
    python scripts/bazel/inventory.py collect --output .aq/tmp/collection.json
    python scripts/bazel/generate_targets.py --collection .aq/tmp/collection.json
    python scripts/bazel/generate_targets.py --check

The checked manifest retains collection evidence. A changed test/conftest requires
fresh collection; --check never invents parametrized IDs or silently drops nodes.
Cross-package Python imports can cycle. Libraries therefore carry their flattened
source closure as data filegroups, keeping one library per owning package without
creating Bazel dependency cycles or a repository-wide Python library.
"""

from __future__ import annotations

import argparse
import ast
import fnmatch
import hashlib
import importlib.util
import json
import re
import shlex
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = "tools/bazel/test_suites.json"
HEADER = "# Generated by scripts/bazel/generate_targets.py; do not edit.\n"
EXCLUDE = ["**/__pycache__/**", "**/*.pyc", "**/BUILD.bazel", "**/node_modules/**"]
PURE_MODULES = {"tests/test_env_scrub.py"}


def dependency_analyzer(root: Path):
    spec = importlib.util.spec_from_file_location(
        "aq_bazel_test_dependencies", ROOT / "scripts/bazel/test_dependencies.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.DependencyAnalyzer(root)


def select_areas(modules: dict, areas: list[str]) -> set[str]:
    selected = set()
    for area in areas:
        matched = {
            path for path, info in modules.items()
            if fnmatch.fnmatchcase(path, area) or area in info.get("areas", [])
        }
        if not matched:
            raise ValueError(f"dependency area matches no test modules: {area}")
        selected.update(matched)
    return selected


def file_label(path: str, libraries: dict, root: Path = ROOT) -> str:
    package = max(
        (p for p in libraries if path.startswith(p + "/")), key=len, default=""
    )
    for directory in Path(path).parents:
        if directory == Path("."):
            break
        if any((root / directory / name).is_file() for name in ("BUILD", "BUILD.bazel")):
            if len(directory.as_posix()) > len(package):
                package = directory.as_posix()
            break
    if package:
        return f"//{package}:" + path.removeprefix(package + "/")
    return "//:" + path


def parsed_tree(path: Path, relative: str, trees: dict | None = None) -> ast.Module:
    if trees is None:
        return ast.parse(path.read_text(encoding="utf-8"))
    if relative not in trees:
        trees[relative] = ast.parse(path.read_text(encoding="utf-8"))
    return trees[relative]


def reads_docs(
    root: Path, paths: list[str], cache: dict | None = None, trees: dict | None = None,
) -> bool:
    """Conservatively recognize documentation inputs, excluding docstrings."""
    cache = {} if cache is None else cache
    for path in paths:
        if path in cache:
            if cache[path]:
                return True
            continue
        if not path.endswith(".py") or not (root / path).is_file():
            continue
        tree = parsed_tree(root / path, path, trees)
        pending = [(tree, False)]
        while pending:
            node, expression = pending.pop()
            expression |= isinstance(node, (ast.Call, ast.Assign, ast.AnnAssign, ast.BinOp))
            if (expression and isinstance(node, ast.Constant) and isinstance(node.value, str)
                    and (node.value == "docs" or node.value.startswith("docs/"))):
                cache[path] = True
                return True
            pending.extend((child, expression) for child in ast.iter_child_nodes(node))
        cache[path] = False
    return False


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_inventory(root: Path):
    spec = importlib.util.spec_from_file_location(
        "aq_bazel_inventory", root / "scripts/bazel/inventory.py"
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def source_files(root: Path) -> list[str]:
    return sorted(
        p.relative_to(root).as_posix()
        for p in (root / "src").rglob("*")
        if p.is_file()
        and "__pycache__" not in p.parts
        and p.name not in {"BUILD", "BUILD.bazel"}
        and p.suffix != ".pyc"
    )


def owner(path: str) -> str:
    parts = path.split("/")
    return "/".join(parts[:2]) if len(parts) > 2 else parts[0]


def module_name(path: str) -> str:
    name = path.removesuffix(".py").replace("/", ".")
    return name.removesuffix(".__init__")


def imports(
    path: Path, relative: str, known: dict[str, str], trees: dict | None = None,
) -> tuple[set[str], bool]:
    """Resolve static and literal dynamic imports; unknown dynamic loads widen."""
    tree = parsed_tree(path, relative, trees)
    found: set[str] = set()
    unknown = False
    package = module_name(relative).split(".")
    if not relative.endswith("/__init__.py"):
        package = package[:-1]
    for node in ast.walk(tree):
        names = []
        if isinstance(node, ast.Import):
            names = [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            base = (
                ".".join(package[: len(package) - node.level + 1]) + "." if node.level else ""
            ) + (node.module or "")
            base = base.rstrip(".")
            names = [base] + [base + "." + alias.name for alias in node.names]
        elif isinstance(node, ast.Call):
            function = (
                "." + node.func.attr
                if isinstance(node.func, ast.Attribute)
                else node.func.id
                if isinstance(node.func, ast.Name)
                else ""
            )
            if function.endswith(("import_module", "__import__", "spec_from_file_location")):
                if (
                    node.args
                    and isinstance(node.args[0], ast.Constant)
                    and isinstance(node.args[0].value, str)
                    and node.args[0].value in known
                ):
                    names = [node.args[0].value]
                else:
                    unknown = True
            if function.endswith(
                (
                    ".rglob",
                    ".glob",
                    ".walk",
                    ".getfixturevalue",
                    ".read_text",
                    ".read_bytes",
                    ".open",
                    ".files",
                    ".open_text",
                )
            ):
                unknown = True
        for name in names:
            for i in range(1, len(name.split(".")) + 1):
                prefix = ".".join(name.split(".")[:i])
                if prefix in known:
                    found.add(known[prefix])
    return found, unknown


def closure(seeds: set[str], edges: dict[str, set[str]]) -> set[str]:
    result = set(seeds)
    pending = list(seeds)
    while pending:
        for dependency in edges.get(pending.pop(), set()) - result:
            result.add(dependency)
            pending.append(dependency)
    return result


def graph(root: Path, modules: dict, fine_grained: set[str] | None = None) -> tuple[dict, dict]:
    analyzer = dependency_analyzer(root) if fine_grained else None
    # Legacy imports, documentation readers and fine-grained fixture discovery
    # inspect the same immutable sources during one graph generation.
    trees = analyzer.trees if analyzer else {}
    files = source_files(root)
    python = [p for p in files if p.endswith(".py")]
    support = [
        p.relative_to(root).as_posix()
        for p in (root / "tests").rglob("*.py")
        if "__pycache__" not in p.parts
    ]
    known = {module_name(p): p for p in python + support}
    edges, dynamic = {}, set()
    fixtures = {p for p in support if not Path(p).name.startswith("test_")}
    for path in python + sorted(fixtures):
        edges[path], unknown = imports(root / path, path, known, trees)
        if unknown:
            dynamic.add(path)
    # A dynamic common fixture already requires every source/test input. Parsing
    # each test body cannot narrow that closure; avoid repeating that expensive
    # work while retaining the full generator_inputs filegroup for these tests.
    if not closure(fixtures, edges) & dynamic:
        for path in sorted(set(support) - fixtures):
            edges[path], unknown = imports(root / path, path, known, trees)
            if unknown:
                dynamic.add(path)
    packages = defaultdict(list)
    for path in files:
        packages[owner(path)].append(path)
    libraries = {}
    for package, own in sorted(packages.items()):
        seeds = {p for p in own if p.endswith(".py")}
        reached = closure(seeds, edges)
        # Runtime registries import names that are not statically discoverable.
        # Flatten the conservative closure into filegroups, never a giant library.
        if reached & dynamic:
            reached.update(python)
        libraries[package] = {
            "files": own,
            "source_packages": sorted({owner(p) for p in reached if p.startswith("src/")}),
        }
    tests = {}
    docs_cache = {}
    for path in sorted(modules):
        reached = closure({path, *fixtures}, edges)
        wide = bool(reached & dynamic)
        packages_used = sorted(
            packages if wide else {owner(p) for p in reached if p.startswith("src/")}
        )
        tests[path] = {
            "libraries": [f"//{p}:library" for p in packages_used],
            "test_sources": sorted(p for p in reached if p.startswith("tests/") and p != path),
            "conservative": wide,
            # Positive pure declarations have focused no-PG behavior checks.
            # All remaining modules are unknown/PG, never inferred pure.
            "postgres": path not in PURE_MODULES,
        }
        if analyzer and path in fine_grained:
            detail = analyzer.discover(path)
            tests[path].update(
                libraries=[], fine_grained=True,
                source_files=detail["source_files"],
                test_sources=detail["test_sources"],
                other_sources=detail["other_sources"],
                data_files=detail["data_files"],
                docs=detail["docs"],
                conservative=detail["conservative"],
                conservative_reasons=detail["conservative_reasons"],
            )
        else:
            # The legacy source closure remains unchanged until its area opts in.
            # Documentation is a separate input and only follows actual readers.
            if path not in edges:
                edges[path], _ = imports(root / path, path, known, trees)
            conftests = [
                p for p in fixtures if Path(p).name == "conftest.py"
                and Path(p).parent in Path(path).parents
            ]
            tests[path]["docs"] = reads_docs(
                root, sorted(closure({path, *conftests}, edges)), docs_cache, trees
            )
    return libraries, tests


def collection_inputs(root: Path) -> dict[str, str]:
    paths = sorted(p for p in (root / "tests").rglob("*.py") if "__pycache__" not in p.parts)
    return {p.relative_to(root).as_posix(): digest(p) for p in paths}


def compact_collection(collection: dict) -> dict:
    if collection.get("exit_code") != 0:
        raise ValueError("collection failed; refusing incomplete node obligations")
    nodes = []
    for node in collection["nodes"]:
        identity = node["nodeid"]
        kind, _, name = node["split_sort_name"][1:-1].partition(" ")
        offset = len(identity) - len(name)
        if offset < 0 or identity[offset:] != name:
            raise ValueError("unsupported pytest split sorting identity")
        nodes.append(
            {
                "nodeid": identity,
                "markers": node["markers"],
                "collection_index": node["collection_index"],
                "sort_kind": kind,
                "sort_offset": offset,
                "keywords": [
                    k
                    for k in node["keywords"]
                    if k and k != ROOT.name and k not in identity and k not in node["markers"]
                ],
            }
        )
    ids = [n["nodeid"] for n in nodes]
    if len(ids) != len(set(ids)) or not ids:
        raise ValueError("collection must contain unique, nonempty node IDs")
    return {
        "nodes": nodes,
        "source_files": collection["source_files"],
        "collection_reports": collection["collection_reports"],
        "evidence": {
            key: collection[key]
            for key in (
                "source_head",
                "pytest_version",
                "python_version",
                "configuration_sha256",
                "tool_sha256",
            )
        },
    }


def expanded_nodes(collection: dict) -> list[dict]:
    return [
        {
            **node,
            "module": node["nodeid"].split("::")[0],
            "keywords": [node["nodeid"], *node["markers"], *node["keywords"]],
            "split_sort_name": "<"
            + node["sort_kind"]
            + " "
            + node["nodeid"][node["sort_offset"] :]
            + ">",
        }
        for node in collection["nodes"]
    ]


def suite_name(job: dict, command: str) -> str:
    matrix = job["matrix"]
    if job["job"] == "e2e-cli":
        return "e2e_" + matrix["group"]
    if "test_cli_startup_offline.py" in command:
        return "cli_startup"
    name = matrix["suite"]["name"]
    return {
        "cli-conformance": "cli",
        "migration-and-slow": "migration_slow",
        "postgres-integration": "postgres",
    }.get(name, name.replace("-", "_").replace("/8", ""))


def make_manifest(root: Path, collection: dict, libraries: dict, tests: dict) -> dict:
    inventory = load_inventory(root)
    catalogue = json.loads((root / "tests/selection_catalogue.json").read_text())
    default = inventory.option(
        shlex.split(
            tomllib.loads((root / "pyproject.toml").read_text())["tool"]["pytest"]["ini_options"][
                "addopts"
            ]
        ),
        "-m",
        "",
    )
    durations = json.loads((root / ".test_durations").read_text())
    collected_nodes = expanded_nodes(collection)
    indices = {node["nodeid"]: i for i, node in enumerate(collected_nodes)}
    suites = {}
    for job in inventory.workflow_inventory(root):
        for step in job["steps"]:
            if step["matrix_enabled"] is False:
                continue
            for line in step["command"].splitlines():
                if not re.match(r"\s*(pytest\b|aq test\b|python -m pytest\b)", line):
                    continue
                key = suite_name(job, line)
                if key in suites:
                    raise ValueError(f"duplicate workflow obligation: {key}")
                nodes = inventory.select_nodes(collected_nodes, line, default)
                if inventory.option(shlex.split(line), "--splits"):
                    nodes, split_version = inventory.partition(
                        collected_nodes, nodes, shlex.split(line), durations
                    )
                members = defaultdict(list)
                for node in nodes:
                    members[node.split("::")[0]].append(indices[node])
                suites[key] = {
                    "command": line,
                    "marker": inventory.option(shlex.split(line), "-m", default),
                    "modules": dict(sorted(members.items())),
                    "targets": [target(p, key) for p in sorted(members)],
                    "perf_strict": key == "cli_startup",
                    "split_version": split_version
                    if inventory.option(shlex.split(line), "--splits")
                    else None,
                }
    # Focused worker invocations retain the default exclusions. --all remains
    # explicit/manual; collection includes opt-in nodes not covered by any arm.
    for key, marker in (("module", default), ("all_nodes", "")):
        members = defaultdict(list)
        for node in inventory.select_nodes(
            collected_nodes, f"pytest tests/ -m '{marker}'", default
        ):
            members[node.split("::")[0]].append(indices[node])
        suites[key] = {
            "command": None,
            "marker": marker,
            "modules": dict(sorted(members.items())),
            "targets": [target(p, key) for p in sorted(members)],
            "perf_strict": False,
        }
    modules = {}
    collected = defaultdict(list)
    for i, node in enumerate(collected_nodes):
        collected[node["module"]].append(i)
    for path, info in catalogue["modules"].items():
        modules[path] = {
            **tests[path],
            "areas": info["areas"],
            "markers": info["markers"],
            "nodes": collected[path],
            "target": target(path, "module"),
            "targets": {
                key: target(path, key) for key, suite in suites.items() if path in suite["modules"]
            },
        }
        # Collection-skipped modules still have an explicit, fail-closed focused
        # target. Their collection reports remain evidence, never invented nodes.
        modules[path]["targets"].setdefault("module", target(path, "module"))
    return {
        "schema_version": 1,
        "generator_version": 1,
        "default_marker": default,
        "collection": collection,
        "catalogue_sha256": digest(root / "tests/selection_catalogue.json"),
        "workflow_sha256": digest(root / ".github/workflows/tests.yml"),
        "durations_sha256": digest(root / ".test_durations"),
        "libraries": libraries,
        "modules": modules,
        "suites": suites,
        "aliases": {
            "cli": ["cli"],
            "default": [f"default_{i}" for i in range(1, 9)],
            "postgres": ["postgres"],
            "migration_slow": ["migration_slow"],
            "cli_startup": ["cli_startup"],
            "e2e": ["e2e_" + group for group in ("claims", "cli", "graphs", "failover")],
        },
    }


def target(path: str, suite: str) -> str:
    name = path.removeprefix("tests/").removesuffix(".py").replace("/", "__")
    return "//tests:" + name + ("" if suite == "module" else "__" + suite)


def lines_list(values: list[str], indent: str = "    ") -> str:
    return (
        "[\n"
        + "".join(indent + "    " + json.dumps(v, ensure_ascii=False) + ",\n" for v in values)
        + indent
        + "]"
    )


def replace_section(existing: str, name: str, content: str) -> str:
    """Replace only our section; preserve sibling generators' appended targets."""
    begin, end = f"# BEGIN B1 {name}\n", f"# END B1 {name}\n"
    section = begin + content.rstrip() + "\n" + end
    if begin not in existing:
        return existing.rstrip() + "\n\n" + section
    before, tail = existing.split(begin, 1)
    after = tail.split(end, 1)[1] if end in tail else ""
    return before + section + after


def manifest_json(manifest: dict) -> str:
    """Keep each independently collected node on one reviewable JSON row."""
    marker = "__AQ_B1_NODE_TABLE__"
    table = manifest["collection"]["nodes"]
    body = json.dumps(
        {**manifest, "collection": {**manifest["collection"], "nodes": marker}},
        indent=2,
        sort_keys=True,
    )
    rows = (
        "[\n"
        + ",\n".join("      " + json.dumps(node, sort_keys=True) for node in table)
        + "\n    ]"
    )
    return body.replace(json.dumps(marker), rows, 1) + "\n"


def render(root: Path, manifest: dict) -> dict[str, str]:
    output = {}
    libraries = manifest["libraries"]
    fine_inputs = {
        path
        for info in manifest["modules"].values() if info.get("fine_grained")
        for path in info["source_files"] + info["other_sources"] + info["data_files"]
    }
    file_labels = {path: file_label(path, libraries, root) for path in fine_inputs}
    for package, info in libraries.items():
        own = [p.removeprefix(package + "/") for p in info["files"]]
        children = [p for p in libraries if p != package and p.startswith(package + "/")]
        inputs = 'glob(["**"], exclude = ' + json.dumps(EXCLUDE) + ")"
        if children:
            inputs += " + " + repr([f"//{p}:generator_inputs" for p in children])
        content = HEADER + 'load("@rules_python//python:defs.bzl", "py_library")\n'
        content += 'load("@pypi//:requirements.bzl", "all_requirements")\n'
        content += 'package(default_visibility = ["//visibility:public"])\n'
        content += f'filegroup(name = "generator_inputs", srcs = {inputs})\n'
        content += 'filegroup(name = "sources", srcs = ' + lines_list(own) + ")\n"
        content += 'exports_files(' + lines_list(own) + ')\n'
        content += 'filegroup(name = "resources", srcs = ' + lines_list(
            [p for p in own if not p.endswith(".py")]
        ) + ')\n'
        content += (
            'py_library(\n    name = "library",\n    srcs = '
            + lines_list([p for p in own if p.endswith(".py")])
            + ",\n"
        )
        content += '    imports = ["' + "/".join([".."] * len(package.split("/"))) + '"],\n'
        content += (
            "    deps = all_requirements,\n    data = "
            + lines_list(
                [f"//{p}:sources" for p in info["source_packages"] if p != package]
                + [p for p in own if not p.endswith(".py")]
            )
            + ",\n)\n"
        )
        output[package + "/BUILD.bazel"] = content
    parts = [
        HEADER,
        'load("//tools/bazel:pytest.bzl", "aq_module_tests")\n',
        'package(default_visibility = ["//visibility:public"])\n',
        'filegroup(name = "generator_inputs", srcs = glob(["**"], exclude = '
        + json.dumps(EXCLUDE)
        + "))\n",
        'filegroup(name = "fixtures", srcs = glob(["**"], exclude = '
        + json.dumps(EXCLUDE + ["**/test_*.py"])
        + "))\n",
    ]
    for path, info in manifest["modules"].items():
        name = info["target"].split(":")[1]
        node_ids = [manifest["collection"]["nodes"][i]["nodeid"] for i in info["nodes"]]
        local_indices = {ref: i for i, ref in enumerate(info["nodes"])}
        data = [path.removeprefix("tests/"), "//:python_repository_data"]
        data += [p.removeprefix("tests/") for p in info["test_sources"]]
        if info.get("fine_grained"):
            inputs = info["source_files"] + info["other_sources"] + info["data_files"]
            # A file may be both imported Python and data inspected by a test.
            # Normalize equivalent labels before deduplicating the attribute.
            data += [file_labels[p].removeprefix("//tests:") for p in inputs]
            data += [f"//{p}:resources" for p in sorted({
                owner(p) for p in info["source_files"]
            })]
        if not info.get("fine_grained") or info["conservative"]:
            data += [":fixtures"]
        if info.get("docs"):
            data += ["//:python_documentation_data"]
        if info["conservative"] and not info.get("fine_grained"):
            data += [":generator_inputs"]
        parts += [
            "\naq_module_tests(\n    name = " + json.dumps(name) + ",\n",
            "    module = " + json.dumps(path) + ",\n",
            "    nodes = " + lines_list(node_ids) + ",\n",
            "    postgres = " + str(info["postgres"]) + ",\n",
            "    deps = " + lines_list(info["libraries"]) + ",\n",
            "    data = " + lines_list(sorted(set(data))) + ",\n",
            "    obligations = [\n",
        ]
        for suite, label in info["targets"].items():
            tags = ["aq-python", "aq-suite-" + suite]
            selected = [
                local_indices[i] for i in manifest["suites"][suite]["modules"].get(path, [])
            ]
            if suite != "module" or not selected:
                tags.append("manual")
            obligation = {
                "name": label.split(":")[1],
                "suite": suite,
                "tags": tags,
                "marker": manifest["suites"][suite]["marker"],
                "nodes": selected,
                "perf_strict": manifest["suites"][suite]["perf_strict"],
            }
            parts.append("        " + repr(obligation) + ",\n")
        parts.append("    ],\n)\n")
    content = "".join(parts)
    output["tests/BUILD.bazel"] = content
    output[MANIFEST] = manifest_json(manifest)
    # Root stanza is additive: B2/B3 own the surrounding root targets.
    root_build = (root / "BUILD.bazel").read_text()

    data_load = 'load("//tools/bazel:python_data.bzl", "python_repository_data")\n'
    if data_load not in root_build:
        root_build = data_load + root_build
    root_build = replace_section(
        root_build,
        "PYTHON DATA",
        HEADER + 'python_repository_data(name = "python_repository_data")\n',
    )
    output["BUILD.bazel"] = root_build
    output["tools/bazel/python_data.bzl"] = (
        HEADER
        + """def python_repository_data(name):
    native.filegroup(
        name = name,
        srcs = native.glob(
            ["*", ".github/**", "scripts/**", "migrations/**", "packages/aq-client/**"],
            exclude = ["BUILD.bazel", "**/__pycache__/**", "**/*.pyc", "**/node_modules/**"],
            allow_empty = True,
        ) + ["//tools/bazel:repository_inputs"],
        visibility = ["//visibility:public"],
    )
    native.filegroup(
        name = "python_documentation_data",
        srcs = native.glob(["docs/**"], exclude = ["**/BUILD.bazel"]),
        visibility = ["//visibility:public"],
    )
"""
    )
    # B2 consumes this input aggregator; package globs stop at subpackages.
    aggregate = HEADER + 'filegroup(\n    name = "python_generator_inputs",\n    srcs = '
    aggregate += lines_list(["//src:generator_inputs", "//tests:generator_inputs"])
    aggregate += ',\n    visibility = ["//visibility:public"],\n)\n'
    tools = (root / "tools/bazel/BUILD.bazel").read_text()
    runtime_load = 'load(":pytest.bzl", "aq_python_runtime")\n'
    if runtime_load not in tools:
        tools = runtime_load + tools
    section = aggregate
    section += (
        'filegroup(name = "repository_inputs", srcs = glob(["**"], exclude = '
        + json.dumps(EXCLUDE)
        + '), visibility = ["//visibility:public"])\n'
    )
    section += """aq_python_runtime(name = "pytest_runtime")
exports_files(["pytest_main.py", "test_suites.json", "pytest.bzl"])
py_library(
    name = "pytest_launcher",
    srcs = ["runtime.py", "pytest_plugin.py", "pytest_main.py"],
    deps = [":test_environment", ":postgres_cluster", "@pypi//pytest", "@pypi//pytest_asyncio"],
    visibility = ["//visibility:public"],
)
"""
    output["tools/bazel/BUILD.bazel"] = replace_section(tools, "PYTHON TARGETS", section)
    # B3 adds dashboard/generated aliases to this package; expose just Python.
    check_path = root / "checks/BUILD.bazel"
    existing = check_path.read_text() if check_path.exists() else ""
    check = HEADER
    for alias, suites in manifest["aliases"].items():
        labels = sorted(
            {label for suite in suites for label in manifest["suites"][suite]["targets"]}
        )
        check += (
            "test_suite(\n    name = "
            + json.dumps(alias)
            + ",\n    tests = "
            + lines_list(labels)
            + ',\n    tags = ["manual"],\n)\n'
        )
    output["checks/BUILD.bazel"] = replace_section(existing, "PYTHON SUITES", check).lstrip()
    # Direct file dependencies need explicit exports even when a public filegroup
    # already contains them. Query accepts private files; analysis rejects them.
    exports: dict[str, set[str]] = {}
    for label in file_labels.values():
        package, name = label[2:].split(":", 1)
        if package in libraries or package == "tests":
            continue
        exports.setdefault(package, set()).add(name)
    for package, names in sorted(exports.items()):
        directory = root / package
        filename = "BUILD.bazel" if (directory / "BUILD.bazel").exists() else "BUILD"
        relative = str(Path(package) / filename)
        existing = output.get(relative, (directory / filename).read_text())
        section = HEADER + "exports_files(" + lines_list(sorted(names)) + ")\n"
        output[relative] = replace_section(existing, "PYTHON INPUT EXPORTS", section)
    return output


def generate(
    root: Path, collection: dict | None = None, areas: list[str] | None = None,
) -> dict[str, str]:
    catalogue = json.loads((root / "tests/selection_catalogue.json").read_text())
    existing = json.loads((root / MANIFEST).read_text()) if (root / MANIFEST).exists() else {}
    selected = set(existing.get("fine_grained_modules", []))
    selected.update(select_areas(catalogue["modules"], areas or []))
    selected.intersection_update(catalogue["modules"])
    if collection is None:
        collection = json.loads((root / MANIFEST).read_text())["collection"]
    else:
        collection = compact_collection(collection)
    if collection["source_files"] != collection_inputs(root):
        raise ValueError(
            "test/fixture source drift; refresh --collection before generating targets"
        )
    libraries, tests = graph(root, catalogue["modules"], selected)
    manifest = make_manifest(root, collection, libraries, tests)
    manifest["fine_grained_modules"] = sorted(selected)
    return render(root, manifest)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--collection", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--area", action="append", default=[],
        help="Opt in a catalogue area or quoted test-path glob; repeatable and retained in manifest",
    )
    args = parser.parse_args()
    try:
        outputs = generate(
            ROOT, json.loads(args.collection.read_text()) if args.collection else None, args.area
        )
        stale = []
        for relative, content in outputs.items():
            path = ROOT / relative
            if args.check:
                if not path.exists() or path.read_text() != content:
                    stale.append(relative)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        if stale:
            raise ValueError("Bazel target drift: " + ", ".join(stale))
    except (ValueError, OSError) as exc:
        print(exc, file=sys.stderr)
        return 1
    print(
        f"{len(outputs)} Python graph/manifest outputs {'checked' if args.check else 'generated'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
